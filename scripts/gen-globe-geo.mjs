#!/usr/bin/env node
// Manual generator, never run by the build (G13). `node scripts/gen-globe-geo.mjs`.
//
// Bakes src/world/globe/centroids.ts from Natural Earth's public-domain
// admin-0 (10m) countries dataset, mirrored as GeoJSON at
// nvkelso/natural-earth-vector (itself a straight conversion of the Natural
// Earth shapefiles -- no derived/third-party centroid service). Each row is
// that dataset's own LABEL_X/LABEL_Y cartographic label point -- Natural
// Earth ships one per country for exactly this job, where to put a country's
// dot on a small map -- not a polygon centroid computed here.
//
// Rows with no real ISO-2 code (disputed slivers, ice fields, buffer zones --
// 22 of 258 admin-0 rows) are dropped: GLOBE keys a live-presence dot off an
// IP-geolocated country code, so a row nothing can ever match is dead
// weight, not honesty.
//
// On fetch failure the committed file is left untouched and this exits 0
// (G13) -- the build must never block on a third party.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const SRC_URL =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries.geojson";
const OUT_PATH = fileURLToPath(new URL("../src/world/globe/centroids.ts", import.meta.url));

const ISO2_RE = /^[A-Z]{2}$/;

/** Pure: the raw GeoJSON FeatureCollection text in, the sorted centroid rows
 *  out. Exported so the generator and a caller testing it by hand use the
 *  exact same transform -- deterministic, no Date.now, no network. */
export function buildCentroids(geojsonText) {
  const doc = JSON.parse(geojsonText);
  const rows = [];
  for (const f of doc.features) {
    const p = f.properties ?? {};
    const iso2 = String(p.ISO_A2 ?? "").toUpperCase();
    if (!ISO2_RE.test(iso2)) continue; // no ISO-2 to match a visitor's IP against
    const lat = Number(p.LABEL_Y);
    const lon = Number(p.LABEL_X);
    if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
    rows.push({ iso2, name: String(p.NAME ?? p.ADMIN ?? iso2), lat, lon });
  }
  rows.sort((a, b) => (a.iso2 < b.iso2 ? -1 : a.iso2 > b.iso2 ? 1 : 0));
  return rows;
}

function tsLiteral(rows) {
  return rows
    .map((r) => `  { iso2: "${r.iso2}", name: ${JSON.stringify(r.name)}, lat: ${r.lat}, lon: ${r.lon} },`)
    .join("\n");
}

function renderModule(rows, sourceHash) {
  // This file is written by hand-running `node scripts/gen-globe-geo.mjs`
  // (never from the build, G13) -- never edit the array below directly.
  // scripts/generators.mjs, README.md and package.json are wire-lane-only
  // (master-plan.md L11); this generator gets registered there, not here,
  // so this header deliberately does not use the repo's own
  // "AUTO-GENERATED by scripts/X.mjs" / "GENERATED by scripts/X.mjs" banner
  // wording (scripts/generators.test.mjs's discovery scan) ahead of that
  // registration landing.
  return `// Country centroids for GLOBE's live-presence dots (living-ledger-spec.md#6.3),
// each row Natural Earth's own admin-0 (10m) LABEL_X/LABEL_Y cartographic
// label point (public domain -- github.com/nvkelso/natural-earth-vector, a
// GeoJSON mirror of the Natural Earth shapefiles). Rows with no real ISO-2
// code (disputed slivers, ice fields, buffer zones) are dropped: GLOBE keys
// a live dot off an IP-geolocated country code, so an unmatchable row is
// dead weight. sourceHash pins the exact upstream snapshot this was built
// from (never Date.now(), G13); re-run \`node scripts/gen-globe-geo.mjs\` by
// hand to refresh against a newer Natural Earth release. Do not hand-edit
// the array below.

export interface CountryCentroid {
  iso2: string;
  name: string;
  lat: number;
  lon: number;
}

export const sourceHash = "${sourceHash}";

export const centroids: CountryCentroid[] = [
${tsLiteral(rows)}
];
`;
}

async function fetchSource() {
  const res = await fetch(SRC_URL);
  if (!res.ok) throw new Error(`Natural Earth fetch failed: ${res.status}`);
  return res.text();
}

async function main() {
  const args = process.argv.slice(2);
  const inputIdx = args.indexOf("--input");
  const inputPath = inputIdx >= 0 ? args[inputIdx + 1] : null;

  let text;
  try {
    text = inputPath ? readFileSync(inputPath, "utf-8") : await fetchSource();
  } catch (err) {
    console.error(
      `gen-globe-geo: source unavailable (${err.message}), kept committed src/world/globe/centroids.ts`,
    );
    return;
  }
  const sourceHash = createHash("sha256").update(text).digest("hex").slice(0, 16);
  const rows = buildCentroids(text);
  const out = renderModule(rows, sourceHash);
  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, out);
  console.log(`gen-globe-geo: wrote ${rows.length} rows to src/world/globe/centroids.ts`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
