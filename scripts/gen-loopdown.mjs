// Refresh the writing snapshot from the public registry. A failed fetch or
// conflicting identity preserves the previous snapshot and fails the refresh.
// Normal builds consume that snapshot without requiring the source network.
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { fetchWithTimeout } from "./lib/net.mjs";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = join(root, "src", "data", "writing.ts");
const SRC = "https://raw.githubusercontent.com/darkpandawarrior/the-loopdown/main/data/registry.json";
// Public, keyless, per_page=100 covers the whole feed in one call (P1-07b).
const DEVTO_ARTICLES = "https://dev.to/api/articles?username=darkpandawarrior&per_page=100";

const banner =
  "// AUTO-GENERATED by scripts/gen-loopdown.mjs — do not edit by hand.\n" +
  "// Source: github.com/darkpandawarrior/the-loopdown (data/registry.json)\n";

// Kept named PostLinks/links, not renamed to "engagement": WritingView.tsx
// already reads l.links?.[platform] to decide which icons to show, and this
// lane fixes what the field is POPULATED from (see engagementOf below), not
// its name — a rename would touch a file this lane does not own for no
// behavioural gain.
const TYPES = `export type PostLinks = { devto?: string; linkedin?: string; medium?: string; hashnode?: string };
export type DevtoEngagement = { reactions: number; comments: number };
export type Engagement = { devto?: DevtoEngagement };
export type Lesson = { title: string; slug: string; pillar?: string; series?: string; status?: string; created?: string; live?: string; tags?: string[]; project: string | null; links: PostLinks; engagement?: Engagement; engagementStale?: boolean };
export type Series = { id: string; title: string; episodes: number };
export type Archive = { title: string; slug: string; form?: string; era?: string; words?: string | number; tags?: string[]; blurb?: string };
export type CastMember = { id: string; appearances: number };
export type Writing = { lessons: Lesson[]; series: Series[]; archive: Archive[]; cast: CastMember[] };
`;

const COLLECTIONS = ["lessons", "series", "archive", "cast"];

/**
 * The four collections as the committed writing.ts already has them, or null
 * when there is no readable previous file.
 *
 * The brace is anchored past `export const writing` deliberately. This file
 * emits its TYPES first, so the FIRST `{` in it opens the PostLinks type and
 * slicing from there gives TypeScript, not JSON — the parse would throw, the
 * catch would hand back null, and the guard below would pass on every run
 * while never once being able to fail.
 */
export function previous() {
  try {
    const s = readFileSync(outPath, "utf8");
    return JSON.parse(s.slice(s.indexOf("{", s.indexOf("export const writing")), s.lastIndexOf("}") + 1));
  } catch {
    return null;
  }
}

/** Which of the four collections came back smaller than the file on disk. */
export function shrinkage(data, prev) {
  return prev ? COLLECTIONS.filter((k) => data[k].length < (prev[k]?.length ?? 0)) : [];
}

/** Exact duplicate source records collapse; conflicting identities fail before writing. */
export function uniqueRecords(records, key) {
  const seen = new Map();
  for (const record of records) {
    const id = record?.[key];
    if (typeof id !== "string" || !id.trim()) throw new Error(`Missing ${key} in source record`);
    if (seen.has(id) && JSON.stringify(seen.get(id)) !== JSON.stringify(record)) {
      throw new Error(`Conflicting source records for ${key}=${id}`);
    }
    seen.set(id, record);
  }
  return [...seen.values()];
}

/**
 * Per-platform publish URLs, keyed to the shape the site renders (devto,
 * hashnode, medium, linkedin) rather than the registry's own `url_*` prefix.
 *
 * The registry ALSO ships an empty `links` object on every lesson — a
 * leftover shape from before per-platform URLs existed — which is why the
 * previous version of this function read `l.links` and got `{}` back even on
 * lessons the source's own `url_devto` field showed as published. That is the
 * one bug this lane's brief calls out by name.
 */
export function engagementOf(l) {
  const e = {};
  if (l.url_devto) e.devto = l.url_devto;
  if (l.url_hashnode) e.hashnode = l.url_hashnode;
  if (l.url_medium) e.medium = l.url_medium;
  if (l.url_linkedin) e.linkedin = l.url_linkedin;
  return e;
}

/**
 * dev.to's engagement per article, keyed by canonical URL. `null` means the
 * fetch itself failed (network/HTTP) and callers fall back per-lesson to
 * whatever was already committed, flagged stale. An article dev.to simply
 * doesn't list back (renamed slug, unpublished) is NOT a fetch failure — it
 * resolves to "not found" for that one URL, handled the same stale way by
 * devtoEngagementFor below so one dropped article can't sink the whole run.
 */
export async function fetchDevtoEngagement() {
  try {
    // No retries: this is best-effort ornamentation with a solid fallback
    // (the committed numbers, flagged stale), so a slow retry loop here would
    // only add wall-clock time to every build for a non-critical field.
    const res = await fetchWithTimeout(DEVTO_ARTICLES, {}, { retries: 0 });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const articles = await res.json();
    return new Map(articles.map((a) => [a.url, { reactions: a.public_reactions_count ?? 0, comments: a.comments_count ?? 0 }]));
  } catch (e) {
    console.warn(`gen-loopdown: dev.to engagement fetch failed (${e.message}); keeping committed numbers`);
    return null;
  }
}

/**
 * Per-lesson engagement decision: fresh numbers when dev.to has them for this
 * URL, else the previously-committed numbers marked stale, else nothing.
 */
export function devtoEngagementFor(url, devtoByUrl, prevDevto) {
  const fresh = url && devtoByUrl ? devtoByUrl.get(url) : undefined;
  if (fresh) return { devto: fresh, engagementStale: false };
  if (prevDevto) return { devto: prevDevto, engagementStale: true };
  return { devto: undefined, engagementStale: false };
}

function emit(reg, devtoByUrl) {
  const pick = (o, keys) => Object.fromEntries(keys.filter((k) => o?.[k] !== undefined).map((k) => [k, o[k]]));
  const prevBySlug = new Map((previous()?.lessons ?? []).map((l) => [l.slug, l]));
  const data = {
    lessons: uniqueRecords(reg.lessons || [], "slug").map((l) => {
      const links = engagementOf(l);
      const { devto, engagementStale } = devtoEngagementFor(links.devto, devtoByUrl, prevBySlug.get(l.slug)?.engagement?.devto);
      return {
        ...pick(l, ["title", "slug", "pillar", "series", "status", "created", "live", "tags"]),
        project: l.project || null,
        links,
        ...(devto ? { engagement: { devto } } : {}),
        ...(engagementStale ? { engagementStale: true } : {}),
      };
    }),
    series: uniqueRecords(reg.series || [], "id").map((s) => pick(s, ["id", "title", "episodes"])),
    archive: uniqueRecords(reg.archive || [], "slug").map((a) => pick(a, ["title", "slug", "form", "era", "words", "tags", "blurb"])),
    cast: uniqueRecords(reg.cast || [], "id").map((c) => pick(c, ["id", "appearances"])),
  };

  // The rule is regression, not emptiness. HTTP status is the only failure this
  // script tested, and a 200 is not proof of a good answer: a truncated file, a
  // renamed top-level key or a repo mid-rewrite all arrive as a success, and
  // every branch above falls back to `[]`, so the whole hub blanks without one
  // error being raised. A published lesson does not un-publish, and neither
  // does a series, an archive entry or a cast member, so a shrink in ANY of the
  // four is a failure in effect even when it is not one in code.
  const shrunk = shrinkage(data, previous());
  if (shrunk.length) {
    // Preserve the last good snapshot, but make the refresh failure observable.
    console.warn(
      `gen-loopdown: registry returned fewer ${shrunk.join("/")} than the committed file — ` +
      `keeping src/data/writing.ts`,
    );
    process.exit(1);
  }

  writeFileSync(
    outPath,
    banner + TYPES +
      `export const writing: Writing = ${JSON.stringify(data, null, 2)};\n\n` +
      `export const writingGeneratedAt = "${new Date().toISOString().slice(0, 10)}";\n`,
  );
  const live = data.lessons.filter((l) => l.links.devto).length;
  console.log(
    `gen-loopdown: ${data.lessons.length} lessons (${live} live on dev.to), ${data.series.length} series, ` +
      `${data.archive.length} archive → src/data/writing.ts`,
  );
}

// Only when run as a generator. The test imports this module for `previous`
// and `shrinkage`, and an import must not reach for the network.
if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  try {
    // Independent sources, fetched concurrently: dev.to engagement failing
    // never blocks the registry (fetchDevtoEngagement already swallows its
    // own errors and returns null), and this halves wall-clock time.
    const [res, devtoByUrl] = await Promise.all([fetchWithTimeout(SRC), fetchDevtoEngagement()]);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    emit(await res.json(), devtoByUrl);
  } catch (e) {
    process.exitCode = 1;
    if (existsSync(outPath)) {
      console.warn(`gen-loopdown: fetch failed (${e.message}); keeping existing src/data/writing.ts`);
    } else {
      console.error(`gen-loopdown: fetch failed (${e.message}); no snapshot available`);
    }
  }
}
