// Owns only the marked README table. All feature rows come from the manifest.
import { readFileSync, writeFileSync } from "node:fs";
import { CARRY_OVER } from "../../src/world/v2/carryOver.ts";

const readme = new URL("../../README.md", import.meta.url);
const source = readFileSync(readme, "utf8");
const start = "<!-- AUTOGEN:WORLD-CARRY-OVER:START -->";
const end = "<!-- AUTOGEN:WORLD-CARRY-OVER:END -->";
const from = source.indexOf(start);
const to = source.indexOf(end);
if (from < 0 || to < from || source.split(start).length !== 2 || source.split(end).length !== 2) {
  throw new Error("README must contain exactly one ordered pair of world carry-over markers");
}

const cell = (text) => text.replaceAll("|", "&#124;").replace(/\r?\n/g, " ");
const rows = CARRY_OVER.map((entry) => {
  const states = ["ported", "degraded", "dropped"].map((status) => entry.status === status ? "yes" : "");
  const evidence = entry.status === "ported" ? `\`${entry.file}\`` : entry.reason;
  return `| \`${entry.id}\` | ${states.join(" | ")} | | ${cell(evidence)} |`;
});
const table = [
  start,
  "<!-- Generated by scripts/world-v2/gen-carry-over.mjs. Edit carryOver.ts, then regenerate. -->",
  "| v1 feature | Native | Degraded | Dropped | Absent | v2 file or reason |",
  "|---|---|---|---|---|---|",
  ...rows,
  end,
].join("\n");
const generated = source.slice(0, from) + table + source.slice(to + end.length);
if (process.argv.includes("--check")) {
  if (generated !== source) throw new Error("README carry-over table is stale; run npm run gen:world-carry-over");
  console.log(`world carry-over: ${rows.length} README rows match the manifest`);
} else {
  if (generated !== source) writeFileSync(readme, generated);
  console.log(`world carry-over: generated ${rows.length} README rows`);
}
