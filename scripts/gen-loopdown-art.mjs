// Pulls the Loopdown cast portraits and series covers from The Loopdown's own
// repo: lore/assets/manifest.json plus the 21 images it points at, never
// the local ~/Repos/Writing/the-loopdown checkout, which is behind origin and
// carries uncommitted lesson edits (M38).
//
// The manifest's `file` field names a .png (the source the image model
// produced); the repo also ships a pre-optimized .webp sibling at the same
// path, and M38 measured exactly those 21 webp files at 3.39 MB total. This
// fetches the webp directly rather than re-encoding the png, which both
// halves the transfer and keeps this generator out of gen-project-heroes.mjs's
// "the encoder is not byte-stable" trap (see check-generated.mjs).
//
// Same network-optional contract as gen-loopdown.mjs and gen-anthology.mjs,
// with one deliberate difference. Those two exit 1 on a failed refresh so a
// silent blank never ships. This one exits 0 (task spec, M38): a stale cast
// portrait is cosmetic, the committed heavy/loopdown/ and loopdownArt.ts stay
// exactly as they were, and there is nothing here worth failing a build over.
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import sharp from "sharp";

import { fetchWithTimeout } from "./lib/net.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = join(root, "src", "data", "loopdownArt.ts");
const heavyDir = join(root, "heavy", "loopdown");
const REPO = "https://raw.githubusercontent.com/darkpandawarrior/the-loopdown/main";

const banner =
  "// AUTO-GENERATED by scripts/gen-loopdown-art.mjs, do not edit by hand.\n" +
  "// Source: github.com/darkpandawarrior/the-loopdown (lore/assets/manifest.json)\n";

const TYPES = `export type LoopdownArtKind = "cast" | "series";
export type LoopdownArt = {
  id: string;
  kind: LoopdownArtKind;
  src: string; // HEAVY_ASSET_BASE-relative; join with heavy() from lib/assetBase.ts
  alt: string;
  castIds: string[];
  seriesIds: string[];
  width: number;
  height: number;
};
`;

/** Exit 0 on any failure: the committed files stand, per M38. */
function bail(msg) {
  console.warn(`gen-loopdown-art: ${msg}, keeping the committed heavy/loopdown/ and src/data/loopdownArt.ts`);
  process.exit(0);
}

/**
 * The manifest names each source image's .png; the repo ships a pre-optimized
 * .webp sibling at the same path (see this file's header), so every fetch
 * swaps the extension before it goes over the network.
 */
export function webpPathOf(file) {
  return String(file).replace(/\.png$/i, ".webp");
}

/**
 * The regression this generator refuses to ship: REC-9's cast (13) and
 * series (8) counts drifting, or any entry landing with no alt text (an
 * un-captioned portrait an e2e test could never catch, since the <img> would
 * still render). Returns a reason string, or null when the shape is good.
 */
export function shapeProblem(entries) {
  const cast = entries.filter((x) => x.kind === "cast");
  const series = entries.filter((x) => x.kind === "series");
  if (cast.length !== 13 || series.length !== 8) {
    return `manifest shape drifted: ${cast.length} cast / ${series.length} series (expected 13/8)`;
  }
  if (entries.some((x) => !x.alt)) return "an entry has no alt text";
  return null;
}

async function run() {
  let manifest;
  try {
    const res = await fetchWithTimeout(`${REPO}/lore/assets/manifest.json`);
    if (!res.ok) throw new Error(`manifest HTTP ${res.status}`);
    manifest = await res.json();
  } catch (e) {
    return bail(`manifest fetch failed (${e.message})`);
  }
  if (!Array.isArray(manifest) || manifest.length === 0) return bail("manifest carried no entries");

  mkdirSync(join(heavyDir, "cast"), { recursive: true });
  mkdirSync(join(heavyDir, "series"), { recursive: true });

  const entries = [];
  let failed = 0;
  for (const e of manifest) {
    try {
      if (e.kind !== "cast" && e.kind !== "series") throw new Error(`unknown kind "${e.kind}"`);
      if (!e.id || !e.file) throw new Error("missing id or file");
      const webpFile = webpPathOf(e.file);
      const res = await fetchWithTimeout(`${REPO}/${webpFile}`);
      if (!res.ok) throw new Error(`HTTP ${res.status} for ${webpFile}`);
      const buf = Buffer.from(await res.arrayBuffer());
      const meta = await sharp(buf).metadata();
      const name = `${e.id}.webp`;
      writeFileSync(join(heavyDir, e.kind, name), buf);
      entries.push({
        id: e.id,
        kind: e.kind,
        src: `/loopdown/${e.kind}/${name}`,
        alt: (e.alt || "").trim(),
        castIds: Array.isArray(e.cast_ids) ? e.cast_ids : [],
        seriesIds: Array.isArray(e.series_ids) ? e.series_ids : [],
        width: meta.width ?? 0,
        height: meta.height ?? 0,
      });
    } catch (err) {
      failed++;
      console.warn(`gen-loopdown-art: ${e?.id ?? "?"}: ${err.message}`);
    }
  }

  if (failed) return bail(`${failed} asset fetch(es) failed`);

  const problem = shapeProblem(entries);
  if (problem) return bail(problem);

  entries.sort((a, b) => (a.kind === b.kind ? a.id.localeCompare(b.id) : a.kind.localeCompare(b.kind)));

  writeFileSync(
    outPath,
    banner +
      TYPES +
      `export const loopdownArt: LoopdownArt[] = ${JSON.stringify(entries, null, 2)};\n\n` +
      `export const loopdownArtGeneratedAt = "${new Date().toISOString().slice(0, 10)}";\n`,
  );
  const cast = entries.filter((x) => x.kind === "cast").length;
  const series = entries.filter((x) => x.kind === "series").length;
  console.log(`gen-loopdown-art: ${cast} cast + ${series} series → src/data/loopdownArt.ts, heavy/loopdown/`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await run();
}

export { run };
