// Renders the Excelsior magazine PDFs to web-resolution page images so the
// site can host a real reader instead of linking out to MANIT's flipbook.
//
// NOT part of prebuild. This is a manual, occasional tool (like the showcase
// rebuild): the source PDFs are 30-60 MB each and live on MANIT's CDN, not in
// this repo. It downloads them into a gitignored cache, renders once, and
// skips anything already rendered. The OUTPUT is committed — the build and the
// deploy never need the PDFs or poppler.
//
//   node scripts/gen-excelsior.mjs          # render anything missing
//   node scripts/gen-excelsior.mjs --force  # re-render everything
//
// Requires: poppler (`brew install poppler`) for pdftoppm/pdfinfo.

import { existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cache = join(root, ".excelsior-cache");
const outRoot = join(root, "public", "excelsior", "pages");
const force = process.argv.includes("--force");

// 950px wide, WebP q72 — about 84 KB a page, which is ~33 MB across all three
// issues. AVIF q52 would be ~24 MB, but this is the artefact a recruiter opens
// on an unknown machine, and WebP's support floor is meaningfully older.
const WIDTH = 950;
const QUALITY = 72;
// Rendered at 2x the target width and downsampled: pdftoppm's own scaler is
// nearest-ish and text at 96dpi comes out crunchy.
const DPI = 200;

const EDITIONS = [
  { year: "2021", url: "https://flip.manit.ac.in/wp-content/uploads/2024/04/Excelsior-2021.pdf" },
  { year: "2020", url: "https://flip.manit.ac.in/wp-content/uploads/2024/04/Excelsior-2020.pdf" },
  { year: "2019", url: "https://flip.manit.ac.in/wp-content/uploads/2024/04/Excelsior-2019-.pdf" },
];

const run = (cmd, args) => execFileSync(cmd, args, { stdio: ["ignore", "pipe", "inherit"] }).toString();

mkdirSync(cache, { recursive: true });

const manifest = [];

for (const ed of EDITIONS) {
  const pdf = join(cache, `Excelsior-${ed.year}.pdf`);
  const outDir = join(outRoot, ed.year);

  if (!existsSync(pdf)) {
    console.log(`[excelsior] fetching ${ed.year}…`);
    run("curl", ["-sL", "--fail", "-o", pdf, ed.url]);
  }
  const pages = Number(run("pdfinfo", [pdf]).match(/^Pages:\s+(\d+)$/m)?.[1] ?? 0);
  if (!pages) throw new Error(`[excelsior] could not read a page count for ${ed.year}`);

  const already = existsSync(outDir) ? readdirSync(outDir).filter((f) => f.endsWith(".webp")).length : 0;
  if (already === pages && !force) {
    console.log(`[excelsior] ${ed.year}: ${pages} pages already rendered, skipping`);
    manifest.push({ year: ed.year, pages, source: ed.url });
    continue;
  }

  if (force) rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });

  // Render to a temp dir first so a crash halfway through cannot leave a
  // half-rendered issue that the `already === pages` check would then skip.
  const tmp = join(cache, `render-${ed.year}`);
  rmSync(tmp, { recursive: true, force: true });
  mkdirSync(tmp, { recursive: true });

  console.log(`[excelsior] ${ed.year}: rendering ${pages} pages at ${DPI}dpi…`);
  run("pdftoppm", ["-r", String(DPI), "-jpeg", "-jpegopt", "quality=92", pdf, join(tmp, "p")]);

  const rendered = readdirSync(tmp).filter((f) => f.endsWith(".jpg")).sort();
  let bytes = 0;
  for (const [i, file] of rendered.entries()) {
    const n = String(i + 1).padStart(3, "0");
    const out = join(outDir, `p${n}.webp`);
    await sharp(join(tmp, file)).resize({ width: WIDTH }).webp({ quality: QUALITY }).toFile(out);
    bytes += statSync(out).size;
  }
  rmSync(tmp, { recursive: true, force: true });

  console.log(`[excelsior] ${ed.year}: ${rendered.length} pages, ${(bytes / 1048576).toFixed(1)} MB`);
  manifest.push({ year: ed.year, pages: rendered.length, source: ed.url });
}

manifest.sort((a, b) => b.year.localeCompare(a.year));

writeFileSync(
  join(root, "src", "data", "excelsior.ts"),
  `// AUTO-GENERATED by scripts/gen-excelsior.mjs — do not edit by hand.\n` +
    `// Page images live under public/excelsior/pages/<year>/pNNN.webp.\n` +
    `export interface ExcelsiorEdition {\n` +
    `  year: string;\n` +
    `  pages: number;\n` +
    `  /** MANIT's own copy — the canonical source this was rendered from. */\n` +
    `  source: string;\n` +
    `}\n\n` +
    `export const excelsiorEditions: ExcelsiorEdition[] = ${JSON.stringify(manifest, null, 2)};\n\n` +
    `export const excelsiorPage = (year: string, n: number) =>\n` +
    `  \`/excelsior/pages/\${year}/p\${String(n).padStart(3, "0")}.webp\`;\n`,
);

console.log(`[excelsior] wrote src/data/excelsior.ts — ${manifest.map((m) => `${m.year}:${m.pages}p`).join(" ")}`);
