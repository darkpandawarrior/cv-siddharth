// Scans heavy/projects/<slug>/compare/<set>/ and emits src/data/compareSets.ts.
// Same shape of contract as gen-galleries.mjs: drop files in, they appear — no list to maintain.
//
// Layout:
//   heavy/projects/doori/compare/expenses/1-ledger.png
//   heavy/projects/doori/compare/expenses/2-signal.png
//
// The numeric prefix orders the toggle; the rest of the filename is the label on it. A file
// ending `-dark` pairs with its light sibling rather than becoming its own toggle entry. Ordering is explicit rather than alphabetical because the reading
// order of a comparison is a design decision — "before" belongs on the left, and "paper" sorting
// after "instrument" is an accident of the alphabet, not an argument.
import { readdirSync, writeFileSync, existsSync, statSync } from "node:fs";
import { join, dirname, extname } from "node:path";
import { fileURLToPath } from "node:url";
import { HEAVY_ASSET_BASE } from "../src/lib/assetBase.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// Compare sets moved off Vercel onto GitHub Pages (heavy/) — see assetBase.ts. They are
// full-page before/after screenshots, the single heaviest thing the site shipped same-origin.
const projectsDir = join(root, "heavy", "projects");
if (!existsSync(projectsDir)) {
  if (!existsSync(join(root, "src", "data", "compareSets.ts"))) {
    throw new Error("[gen-compare-sets] Missing source media and committed registry");
  }
  console.log("[gen-compare-sets] Source media absent; retaining committed registry for hosted assets.");
  process.exit(0);
}

// Mirrors gen-galleries.mjs: a .webp/.avif beside a same-basename raster is a gen-images.mjs
// derivative, not a version to compare against.
function isDerivative(dir, file) {
  const ext = extname(file).toLowerCase();
  if (ext === ".avif") return true;
  if (ext !== ".webp") return false;
  const base = file.slice(0, -ext.length);
  return [".png", ".jpg", ".jpeg"].some((e) => existsSync(join(dir, base + e)));
}

function label(file) {
  return file
    .slice(0, file.length - extname(file).length)
    .replace(/^\d+[-_]/, "")
    .replace(/[-_]+/g, " ")
    .trim();
}

const out = {};
if (existsSync(projectsDir)) {
  for (const slug of readdirSync(projectsDir)) {
    const compareDir = join(projectsDir, slug, "compare");
    if (!existsSync(compareDir)) continue;
    const sets = {};
    for (const setName of readdirSync(compareDir)) {
      const setDir = join(compareDir, setName);
      if (!statSync(setDir).isDirectory()) continue;
      const files = readdirSync(setDir)
        .filter((f) => /\.(png|jpe?g|webp)$/i.test(f) && !isDerivative(setDir, f))
        .sort();
      // A `-dark` file pairs with its light sibling instead of becoming its own option: the toggle
      // picks a treatment, the drag compares that treatment's two faces. Two axes, two controls.
      const byLabel = new Map();
      for (const f of files) {
        const raw = label(f);
        const isDark = /\s*dark$/.test(raw);
        const key = isDark ? raw.replace(/\s*dark$/, "").trim() : raw;
        const entry = byLabel.get(key) ?? { label: key, light: null, dark: null };
        const url = `${HEAVY_ASSET_BASE}/projects/${slug}/compare/${setName}/${f}`;
        if (isDark) entry.dark = url;
        else entry.light = url;
        byLabel.set(key, entry);
      }
      // A dark file with no light sibling is a naming mistake, not an option — dropping it keeps a
      // half-pair from rendering as a treatment whose toggle shows nothing.
      const layers = [...byLabel.values()]
        .filter((e) => e.light)
        .map((e) => (e.dark ? e : { label: e.label, light: e.light }));
      if (layers.length >= 1) sets[setName] = layers;
    }
    if (Object.keys(sets).length) out[slug] = sets;
  }
}

const banner =
  "// AUTO-GENERATED by scripts/gen-compare-sets.mjs — do not edit by hand.\n" +
  "// Add versions under heavy/projects/<slug>/compare/<set>/N-label.png and they appear automatically.\n";
writeFileSync(
  join(root, "src", "data", "compareSets.ts"),
  banner +
    "export type CompareOption = { label: string; light: string; dark?: string };\n" +
    `export const compareSets: Record<string, Record<string, CompareOption[]>> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(
  "[gen-compare-sets]",
  Object.fromEntries(
    Object.entries(out).map(([slug, sets]) => [
      slug,
      Object.fromEntries(Object.entries(sets).map(([k, v]) => [k, v.length])),
    ]),
  ),
);
