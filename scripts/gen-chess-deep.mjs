// Second-pass mining of the lichess archive already cached by gen-chess-stats.
//
// The first pass measured what happens INSIDE a game — accuracy, tilt, clutch,
// time-per-decile, the clock thesis. It never touched four fields that were
// sitting in every record: `source` (how the game was found), `clock` (which
// time control), `status` (how it ended), and `opening.ply` (when book ended).
//
// Those four turn out to carry the most uncomfortable findings in the corpus,
// which is the point: this is the same "distrust the aggregate, look at what it
// is made of" move the rest of the site is about.
//
// Reads .chess-cache/lichess-games.json (gitignored, ~6.8 MB, fetched once by
// gen-chess-stats.mjs). No network. If the cache is absent this exits quietly
// and leaves any existing output alone, so a fresh clone still builds.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cache = join(root, ".chess-cache", "lichess-games.json");
const outPath = join(root, "src", "data", "chessDeep.ts");
const ME = "darkpandawarrior";

if (!existsSync(cache)) {
  console.log("[gen-chess-deep] no cache — skipping (run gen-chess-stats first)");
  process.exit(0);
}

const games = JSON.parse(readFileSync(cache, "utf8")).games ?? [];

const sideOf = (g) => {
  const p = g.players ?? {};
  for (const c of ["white", "black"]) if ((p[c]?.user?.id ?? "").toLowerCase() === ME) return c;
  return null;
};
const rows = games
  .map((g) => ({ g, side: sideOf(g) }))
  .filter((r) => r.side)
  .map((r) => ({ ...r, result: r.g.winner === r.side ? "win" : r.g.winner ? "loss" : "draw" }));

/** Win rate over a subset, or null when the sample is too small to mean anything. */
const rate = (pred, min = 100) => {
  const sub = rows.filter(pred);
  if (sub.length < min) return null;
  return { n: sub.length, winRate: +((100 * sub.filter((r) => r.result === "win").length) / sub.length).toFixed(1) };
};
const tally = (fn) => {
  const m = new Map();
  for (const r of rows) m.set(fn(r), (m.get(fn(r)) ?? 0) + 1);
  return [...m.entries()].sort((a, b) => b[1] - a[1]);
};

// 1. How the game was found. Arena is the outlier and it is not close.
const bySource = tally((r) => r.g.source)
  .map(([source, n]) => ({ source, n, ...(rate((r) => r.g.source === source, 90) ?? {}) }))
  .filter((s) => s.winRate != null);

// 2. Time control. The headline: more clock does not help him.
const byTimeControl = tally((r) => `${(r.g.clock?.initial ?? 0) / 60}+${r.g.clock?.increment ?? 0}`)
  .slice(0, 4)
  .map(([tc, n]) => ({ tc, n, ...(rate((r) => `${(r.g.clock?.initial ?? 0) / 60}+${r.g.clock?.increment ?? 0}` === tc, 100) ?? {}) }))
  .filter((t) => t.winRate != null);

// 3. How games end, over EVERY game — not just decided ones.
const total = rows.length;
const byEnding = tally((r) => r.g.status)
  .slice(0, 6)
  .map(([status, n]) => ({ status, n, share: +((100 * n) / total).toFixed(1) }));

// 4. Opening book depth. `ply` is the last move still in a named opening.
const plies = rows.map((r) => r.g.opening?.ply).filter(Boolean).sort((a, b) => a - b);
const medianPly = plies[Math.floor(plies.length / 2)] ?? 0;
const deep = rate((r) => (r.g.opening?.ply ?? 0) >= 8, 90);
const shallow = rate((r) => { const p = r.g.opening?.ply ?? 0; return p > 0 && p <= 4; }, 100);

const out = {
  generatedAt: new Date(JSON.parse(readFileSync(cache, "utf8")).seenAt).toISOString().slice(0, 10),
  sampleSize: total,
  bySource,
  byTimeControl,
  byEnding,
  book: {
    medianPly,
    deep: deep ?? { n: 0, winRate: 0 },
    shallow: shallow ?? { n: 0, winRate: 0 },
  },
};

writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/gen-chess-deep.mjs — do not edit by hand.\n` +
    `// Second-pass mining of fields the first pass never read: how the game was\n` +
    `// found, which time control, how it ended, and when the opening book ran out.\n` +
    `export const chessDeep = ${JSON.stringify(out, null, 2)} as const;\n`,
);

console.log(
  `[gen-chess-deep] ${total.toLocaleString()} games · book exits at ply ${medianPly} · ` +
    `${byEnding[0]?.status} ${byEnding[0]?.share}% → src/data/chessDeep.ts`,
);
