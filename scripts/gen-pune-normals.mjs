#!/usr/bin/env node
/**
 * Writes src/data/generated/puneNormals.ts: the 2015-2025 mean rainfall (mm)
 * for each of the year's 366 calendar days, from Open-Meteo's ERA5 archive.
 * Manual and network, and — unlike every other src/data/generated/*.ts —
 * deliberately NOT wired into scripts/run-pipeline.mjs or generators.mjs: the
 * mean barely moves year to year, so this is a run-by-hand annual refresh,
 * not a build-time call (live-data-spec.md#1.3, #4 R6). Index 0 is Jan 1,
 * index 365 is Dec 31, index 59 is Feb 29 — a fixed leap-year calendar, so a
 * lookup for Mar 1 always lands on index 60 whether or not that lookup's own
 * year is a leap year (skyText.ts's normalMmForDate does the same mapping
 * for a live date).
 */
import { writeFileSync } from "node:fs";

const OUT_PATH = new URL("../src/data/generated/puneNormals.ts", import.meta.url);
const ARCHIVE_URL =
  "https://archive-api.open-meteo.com/v1/archive" +
  "?latitude=18.52&longitude=73.86&start_date=2015-01-01&end_date=2025-12-31" +
  "&daily=precipitation_sum&timezone=Asia%2FKolkata";

/** Same fixed leap-year calendar as skyText.ts's normalMmForDate. */
function dayOfYearIndex(isoDate) {
  const [, m, d] = isoDate.split("-").map(Number);
  const start = Date.UTC(2024, 0, 1);
  return Math.round((Date.UTC(2024, m - 1, d) - start) / 86_400_000);
}

async function main() {
  const res = await fetch(ARCHIVE_URL);
  if (!res.ok) throw new Error(`Open-Meteo archive fetch failed: ${res.status}`);
  const body = await res.json();
  const { time, precipitation_sum: mm } = body.daily;

  const sums = new Array(366).fill(0);
  const counts = new Array(366).fill(0);
  for (let i = 0; i < time.length; i++) {
    const v = mm[i];
    if (v === null || v === undefined) continue;
    const idx = dayOfYearIndex(time[i]);
    sums[idx] += v;
    counts[idx] += 1;
  }
  const normals = sums.map((s, i) => (counts[i] > 0 ? Math.round((s / counts[i]) * 100) / 100 : 0));
  const missing = counts.filter((c) => c === 0).length;
  if (missing > 0) console.warn(`gen-pune-normals: ${missing} of 366 days had no sample`);

  const out = [
    "// AUTO-GENERATED by scripts/gen-pune-normals.mjs, do not edit by hand.",
    "// Open-Meteo historical archive (ERA5), 2015-01-01 to 2025-12-31, Pune",
    "// (18.52, 73.86). Index 0 = Jan 1 ... index 59 = Feb 29 ... index 365 = Dec 31.",
    "// Manual annual refresh: `node scripts/gen-pune-normals.mjs`.",
    "export const PUNE_NORMALS_MM: readonly number[] = [",
    `  ${normals.join(", ")},`,
    "];",
    "",
  ].join("\n");
  writeFileSync(OUT_PATH, out);
  console.log(`gen-pune-normals: wrote 366 rows (${time.length} daily samples, ${missing} empty)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
