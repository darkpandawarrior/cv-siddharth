/**
 * Writes src/data/generated/lighthouse.ts — the third live edge's LHCI half:
 * "/ops renders ... the LHCI summary ... each row carrying source + timestamp
 * + SLA" (target architecture, arch-L14). This lane (arch-L13) only produces
 * the file; wiring it into the /ops page is arch-L14's job.
 *
 * Reads whatever `.lighthouseci/lhr-*.json` the just-completed `npx @lhci/cli
 * autorun` (.github/workflows/lighthouse.yml) left on disk — raw Lighthouse
 * Result JSON, one file per URL in lighthouserc.json's `ci.collect.url` list
 * (numberOfRuns: 1, so exactly one lhr per URL). That directory is
 * .gitignore'd and only ever exists right after a real Lighthouse run, so a
 * checkout with no run yet (a fresh clone, `npm run build` alone) is not an
 * error: this generator degrades to "keep the committed figures", the same
 * posture gen-ops.mjs and gen-project-stats.mjs already use for a similarly
 * environment-dependent source.
 *
 * Deliberately NOT part of the build/refresh/check stages in
 * scripts/generators.mjs: its one real input (.lighthouseci/) doesn't exist
 * until a Lighthouse run has already happened, so it can never run before
 * prebuild/predev, refresh.mjs or check-generated.mjs — only after this
 * workflow's own Lighthouse step. It is still declared there (every gen-*.mjs
 * script must be) with stages: {} — see generators.mjs's own comment on
 * "manual/occasional" nodes for what an empty stages object means.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lhciDir = join(root, ".lighthouseci");
const outFile = join(root, "src", "data", "generated", "lighthouse.ts");
mkdirSync(dirname(outFile), { recursive: true });

// The four metrics this lane's calibration is about, plus the three already
// at "error" (total-byte-weight, script size, CLS) — the same seven
// lighthouserc.json asserts on, read from the SAME raw report rather than a
// second parse of its own numbers.
const AUDITS = /** @type {const} */ ([
  ["performanceScore", null], // category score, read separately below
  ["firstContentfulPaint", "first-contentful-paint"],
  ["largestContentfulPaint", "largest-contentful-paint"],
  ["totalBlockingTime", "total-blocking-time"],
  ["cumulativeLayoutShift", "cumulative-layout-shift"],
  ["totalByteWeight", "total-byte-weight"],
  ["scriptBytes", "resource-summary:script:size"],
]);

function summarise(lhr) {
  const url = new URL(lhr.requestedUrl);
  const row = {
    path: url.pathname + url.search,
    performanceScore: lhr.categories?.performance?.score ?? null,
  };
  for (const [key, auditId] of AUDITS) {
    if (!auditId) continue;
    row[key] = lhr.audits?.[auditId]?.numericValue ?? null;
  }
  return row;
}

function readRuns() {
  if (!existsSync(lhciDir)) return null;
  const files = readdirSync(lhciDir).filter((f) => /^lhr-\d+\.json$/.test(f));
  if (files.length === 0) return null;
  return files
    .map((f) => JSON.parse(readFileSync(join(lhciDir, f), "utf8")))
    .map(summarise)
    .sort((a, b) => a.path.localeCompare(b.path));
}

const runs = readRuns();

if (!runs) {
  if (!existsSync(outFile)) {
    console.log("gen-lighthouse-summary: no .lighthouseci/ run and no committed file yet — writing an empty summary.");
    writeFileSync(
      outFile,
      `// AUTO-GENERATED by scripts/gen-lighthouse-summary.mjs — do not edit by hand.\n` +
        `// No Lighthouse run has produced .lighthouseci/ yet. Run \`npx @lhci/cli autorun\`\n` +
        `// (or let .github/workflows/lighthouse.yml do it) then re-run this generator.\n` +
        `export const lighthouseGeneratedAt = null;\n` +
        `export const lighthouseRuns: LighthouseRun[] = [];\n` +
        `export interface LighthouseRun {\n` +
        `  path: string;\n` +
        `  performanceScore: number | null;\n` +
        `  firstContentfulPaint: number | null;\n` +
        `  largestContentfulPaint: number | null;\n` +
        `  totalBlockingTime: number | null;\n` +
        `  cumulativeLayoutShift: number | null;\n` +
        `  totalByteWeight: number | null;\n` +
        `  scriptBytes: number | null;\n` +
        `}\n`,
    );
  } else {
    console.log("gen-lighthouse-summary: no .lighthouseci/ run this pass — keeping the committed summary.");
  }
  process.exit(0);
}

const generatedAt = new Date().toISOString();
const lines = [
  `// AUTO-GENERATED by scripts/gen-lighthouse-summary.mjs — do not edit by hand.`,
  `// Summarises the .lighthouseci/ raw Lighthouse reports from the most recent`,
  `// \`npx @lhci/cli autorun\` (.github/workflows/lighthouse.yml). Run`,
  `// \`npm run gen:lighthouse-summary\` after a local \`npx @lhci/cli autorun\` to refresh.`,
  `export interface LighthouseRun {`,
  `  path: string;`,
  `  performanceScore: number | null;`,
  `  firstContentfulPaint: number | null;`,
  `  largestContentfulPaint: number | null;`,
  `  totalBlockingTime: number | null;`,
  `  cumulativeLayoutShift: number | null;`,
  `  totalByteWeight: number | null;`,
  `  scriptBytes: number | null;`,
  `}`,
  `export const lighthouseGeneratedAt = ${JSON.stringify(generatedAt)};`,
  `export const lighthouseRuns: LighthouseRun[] = ${JSON.stringify(runs, null, 2)};`,
  "",
];
writeFileSync(outFile, lines.join("\n"));
console.log(`gen-lighthouse-summary: wrote ${runs.length} run(s) to src/data/generated/lighthouse.ts`);
